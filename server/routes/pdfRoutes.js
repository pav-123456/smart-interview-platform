const express = require("express");
const router = express.Router();

const PDFDocument = require("pdfkit");

const InterviewHistory =
  require("../models/InterviewHistory");

// =====================================
// TEST ROUTE
// =====================================

router.get("/", (req, res) => {
  res.send("PDF Route Working");
});

// =====================================
// DOWNLOAD PDF REPORT
// =====================================

router.get(
  "/download/:id",
  async (req, res) => {

    try {

      const interview =
        await InterviewHistory.findById(
          req.params.id
        );

      if (!interview) {

        return res
          .status(404)
          .json({
            success: false,
            message:
              "Interview not found",
          });
      }

      const doc =
        new PDFDocument({
          margin: 50,
        });

      res.setHeader(
        "Content-Type",
        "application/pdf"
      );

      res.setHeader(
        "Content-Disposition",
        `attachment; filename=Interview_Report_${interview._id}.pdf`
      );

      doc.pipe(res);

      // =====================================
      // HEADER
      // =====================================

      doc
        .fontSize(24)
        .text(
          "AI Interview Report",
          {
            align: "center",
          }
        );

      doc.moveDown();

      doc
        .fontSize(12)
        .text(
          `Generated: ${new Date().toLocaleString()}`
        );

      doc.moveDown();

      // =====================================
      // BASIC INFO
      // =====================================

      doc
        .fontSize(18)
        .text(
          "Candidate Performance Summary"
        );

      doc.moveDown();

      doc
        .fontSize(13)
        .text(
          `Role: ${
            interview.role ||
            "Not Available"
          }`
        );

      doc.text(
        `Score: ${
          interview.score ?? 0
        } / 10`
      );

      doc.text(
        `Interview Date: ${
          interview.createdAt
            ? new Date(
                interview.createdAt
              ).toLocaleString()
            : "N/A"
        }`
      );

      doc.moveDown();

      // =====================================
      // QUESTION
      // =====================================

      doc
        .fontSize(16)
        .text(
          "Interview Question"
        );

      doc.moveDown(0.5);

      doc
        .fontSize(12)
        .text(
          interview.question ||
            "No Question Found"
        );

      doc.moveDown();

      // =====================================
      // ANSWER
      // =====================================

      doc
        .fontSize(16)
        .text(
          "Candidate Answer"
        );

      doc.moveDown(0.5);

      doc
        .fontSize(12)
        .text(
          interview.answer ||
            "No Answer Found"
        );

      doc.moveDown();

      // =====================================
      // FEEDBACK
      // =====================================

      doc
        .fontSize(16)
        .text(
          "AI Feedback"
        );

      doc.moveDown(0.5);

      doc
        .fontSize(12)
        .text(
          interview.feedback ||
            "No Feedback Available"
        );

      doc.moveDown();

      // =====================================
      // PERFORMANCE BADGE
      // =====================================

      let badge =
        "Needs Improvement";

      if (
        interview.score >= 8
      ) {
        badge = "Excellent";
      } else if (
        interview.score >= 6
      ) {
        badge = "Good";
      }

      doc
        .fontSize(16)
        .text(
          "Performance Badge"
        );

      doc.moveDown(0.5);

      doc
        .fontSize(14)
        .text(
          `Achievement: ${badge}`
        );

      doc.moveDown(2);

      // =====================================
      // FOOTER
      // =====================================

      doc
        .fontSize(10)
        .text(
          "Generated by Smart Interview Platform",
          {
            align: "center",
          }
        );

      doc.end();

    } catch (error) {

      console.log(
        "PDF ERROR:",
        error
      );

      res
        .status(500)
        .json({
          success: false,
          message:
            "PDF generation failed",
        });
    }
  }
);

module.exports = router;